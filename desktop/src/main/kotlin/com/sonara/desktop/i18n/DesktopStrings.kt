    fun forLanguage(lang: String): AppStrings {
        return when (lang.trim().lowercase(Locale.ROOT)) {
            "deutsch", "de", "german" -> German
            "español", "espanol", "es", "spanish" -> Spanish
            "français", "francais", "fr", "french" -> French
            "türkçe", "turkce", "tr", "turkish" -> Turkish
            "日本語", "ja", "japanese" -> Japanese
            "한국어", "ko", "korean" -> Korean
            "中文", "zh", "chinese" -> Chinese
            "system default", "system", "default" -> {
                when (Locale.getDefault().language) {
                    "de" -> German
                    "es" -> Spanish
                    "fr" -> French
                    "tr" -> Turkish
                    "ja" -> Japanese
                    "ko" -> Korean
                    "zh" -> Chinese
                    else -> English
                }
            }
            else -> English
        }
    }
